# =============================================================================
# STEP 7 — SYSTEMD SERVICE + XVFB
# =============================================================================
step "STEP 7/8 — Set Up systemd Service"

info "Creating Xvfb and intern-hunter systemd services…"
_ssh bash -s << 'REMOTE_SYSTEMD'
set -e

# ── Xvfb virtual display service ─────────────────────────────────────────────
sudo tee /etc/systemd/system/xvfb.service > /dev/null << 'EOF'
[Unit]
Description=Xvfb Virtual Display (for Playwright headless Chromium)
After=network.target

[Service]
Type=forking
User=ubuntu
ExecStart=/usr/bin/Xvfb :99 -screen 0 1280x800x24 -ac +extension RANDR
Restart=on-failure
RestartSec=10

[Install]
WantedBy=multi-user.target
EOF

# ── Intern Hunter agent service ───────────────────────────────────────────────
sudo tee /etc/systemd/system/intern-hunter.service > /dev/null << 'EOF'
[Unit]
Description=Intern Hunter — Automated AI Internship Agent
After=network-online.target xvfb.service
Wants=network-online.target xvfb.service

[Service]
Type=simple
User=ubuntu
WorkingDirectory=/home/ubuntu/intern_hunter
ExecStart=/home/ubuntu/intern_hunter/venv/bin/python agent.py --schedule
Restart=always
RestartSec=60
StartLimitIntervalSec=300
StartLimitBurst=5
StandardOutput=journal
StandardError=journal
Environment=DISPLAY=:99
Environment=HOME=/home/ubuntu

[Install]
WantedBy=multi-user.target
EOF

