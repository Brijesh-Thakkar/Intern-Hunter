#!/usr/bin/env bash
# =============================================================================
#  cloud_deploy.sh — Deploy Intern Hunter to Oracle Cloud Free Tier VM
#  Run from: ~/Desktop/agent/intern_hunter/
#  Usage:    bash cloud_deploy.sh
# =============================================================================
set -euo pipefail
IFS=$'\n\t'

# ── Colours ───────────────────────────────────────────────────────────────────
RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'
CYAN='\033[0;36m'; BOLD='\033[1m'; RESET='\033[0m'

ok()   { echo -e "${GREEN}✅  $*${RESET}"; }
warn() { echo -e "${YELLOW}⚠️   $*${RESET}"; }
err()  { echo -e "${RED}❌  $*${RESET}"; }
info() { echo -e "${CYAN}ℹ️   $*${RESET}"; }
step() { echo -e "\n${BOLD}${CYAN}━━━ $* ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${RESET}"; }

ENV_FILE=".env.deploy"
DEPLOY_DIR="$(cd "$(dirname "$0")" && pwd)"
TARBALL="/tmp/intern_hunter_deploy.tar.gz"
REMOTE_DIR="/home/ubuntu/intern_hunter"

# =============================================================================
# BANNER
# =============================================================================
echo ""
echo -e "${BOLD}${CYAN}"
echo "  ╔══════════════════════════════════════════════════════════╗"
echo "  ║   🚀  INTERN HUNTER — Oracle Cloud Deployment Script    ║"
echo "  ║   Deploys your agent to run 24/7, free forever          ║"
echo "  ╚══════════════════════════════════════════════════════════╝"
echo -e "${RESET}"

# =============================================================================
# STEP 1 — COLLECT CREDENTIALS
# =============================================================================
step "STEP 1/8 — Collect Credentials"
echo ""
echo "  I'll ask for your credentials one by one."
echo "  Passwords are hidden while you type."
echo "  Press Enter to keep an existing value shown in [brackets]."
echo ""

_load_env() {
    if [[ -f "$ENV_FILE" ]]; then
        # shellcheck disable=SC1090
        source "$ENV_FILE"
    fi
}

_save_env() {
    cat > "$ENV_FILE" <<EOF
# Auto-generated by cloud_deploy.sh — contains secrets, never commit this
MISTRAL_API_KEY="${MISTRAL_API_KEY}"
GMAIL_SENDER="${GMAIL_SENDER}"
GMAIL_APP_PASSWORD="${GMAIL_APP_PASSWORD}"
COLLEGE_EMAIL="${COLLEGE_EMAIL}"
TELEGRAM_BOT_TOKEN="${TELEGRAM_BOT_TOKEN}"
TELEGRAM_CHAT_ID="${TELEGRAM_CHAT_ID}"
INTERNSHALA_EMAIL="${INTERNSHALA_EMAIL}"
INTERNSHALA_PASSWORD="${INTERNSHALA_PASSWORD}"
ORACLE_SSH_KEY_PATH="${ORACLE_SSH_KEY_PATH}"
ORACLE_VM_IP="${ORACLE_VM_IP}"
EOF
    chmod 600 "$ENV_FILE"
}

_prompt()       { local v; read -r -p "  $1: " v; echo "${v}"; }
_prompt_secret(){ local v; read -r -s -p "  $1: " v; echo ""; echo "${v}"; }
_prompt_default() {
    local label="$1" default="$2"
    local v
    read -r -p "  ${label} [${default}]: " v
    echo "${v:-$default}"
}

_load_env

echo -e "${BOLD}  ① Mistral AI API Key${RESET} (for job scoring + cover letters)"
MISTRAL_API_KEY="$(_prompt_default "Mistral API key" "${MISTRAL_API_KEY:-}")"
[[ -z "$MISTRAL_API_KEY" ]] && { err "Mistral API key is required."; exit 1; }

echo ""
echo -e "${BOLD}  ② Gmail Sender Address${RESET} (notifications sent from this address)"
GMAIL_SENDER="$(_prompt_default "Gmail address" "${GMAIL_SENDER:-}")"

echo ""
echo -e "${BOLD}  ③ Gmail App Password${RESET} (16-char, from myaccount.google.com/apppasswords)"
echo "     Leave blank to skip email notifications."
GMAIL_APP_PASSWORD="$(_prompt_secret "Gmail App Password")"
[[ -z "$GMAIL_APP_PASSWORD" && -n "${GMAIL_APP_PASSWORD:-}" ]] && GMAIL_APP_PASSWORD="${GMAIL_APP_PASSWORD}"

echo ""
echo -e "${BOLD}  ④ College Email${RESET} (HIGH PRIORITY alerts go here — your IIT Jodhpur email)"
COLLEGE_EMAIL="$(_prompt_default "College email" "${COLLEGE_EMAIL:-}")"

echo ""
echo -e "${BOLD}  ⑤ Telegram Bot Token${RESET} (optional — press Enter to skip)"
TELEGRAM_BOT_TOKEN="$(_prompt_default "Telegram bot token" "${TELEGRAM_BOT_TOKEN:-}")"

echo ""
echo -e "${BOLD}  ⑥ Telegram Chat ID${RESET} (optional — press Enter to skip)"
TELEGRAM_CHAT_ID="$(_prompt_default "Telegram chat ID" "${TELEGRAM_CHAT_ID:-}")"

echo ""
echo -e "${BOLD}  ⑦ Internshala Email${RESET} (used to log into Internshala for auto-apply)"
INTERNSHALA_EMAIL="$(_prompt_default "Internshala email" "${INTERNSHALA_EMAIL:-}")"

echo ""
echo -e "${BOLD}  ⑧ Internshala Password${RESET}"
INTERNSHALA_PASSWORD="$(_prompt_secret "Internshala password")"

echo ""
echo -e "${BOLD}  ⑨ Oracle SSH Key Path${RESET} (path to your .pem or private key file)"
ORACLE_SSH_KEY_PATH="$(_prompt_default "SSH key path" "${ORACLE_SSH_KEY_PATH:-$HOME/.ssh/id_rsa}")"
if [[ ! -f "$ORACLE_SSH_KEY_PATH" ]]; then
    warn "SSH key not found at $ORACLE_SSH_KEY_PATH — will fail at upload step."
