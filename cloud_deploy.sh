fi

echo ""
echo -e "${BOLD}  ⑩ Oracle VM Public IP${RESET} (from your Oracle Cloud Console)"
ORACLE_VM_IP="$(_prompt_default "Oracle VM public IP" "${ORACLE_VM_IP:-}")"
if [[ -z "$ORACLE_VM_IP" ]]; then
    echo ""
    warn "No Oracle VM IP provided. Printing setup instructions:"
    echo ""
    echo "  1. Go to https://cloud.oracle.com → sign in"
    echo "  2. Compute → Instances → Create Instance"
    echo "     • Shape: VM.Standard.A1.Flex (Always Free ARM)"
    echo "     • Image: Ubuntu 22.04"
    echo "     • Add your SSH public key"
    echo "  3. Copy the Public IP from the instance detail page"
    echo "  4. Re-run: bash cloud_deploy.sh"
    echo ""
    echo "  See README_ORACLE_SETUP.md for full instructions."
    exit 1
fi

_save_env
ok "Credentials saved to $ENV_FILE (chmod 600, never committed)"


# =============================================================================
# STEP 2 — ADD .GITIGNORE ENTRIES
# =============================================================================
step "STEP 2/8 — Protect Secrets"

GITIGNORE="$DEPLOY_DIR/.gitignore"
declare -a IGNORE_ENTRIES=(
    ".env.deploy"
    ".env.deploy.*"
    "config.yaml"
    "sessions/"
    "credentials/"
    "data/"
    "*.tar.gz"
    "__pycache__/"
    "*.pyc"
    ".venv/"
    "venv/"
)

touch "$GITIGNORE"
for entry in "${IGNORE_ENTRIES[@]}"; do
    if ! grep -qxF "$entry" "$GITIGNORE" 2>/dev/null; then
        echo "$entry" >> "$GITIGNORE"
    fi
done
ok ".gitignore updated — secrets are protected"


# =============================================================================
# STEP 3 — PACKAGE THE PROJECT
# =============================================================================
step "STEP 3/8 — Package Project"

info "Creating deployment tarball (excluding data/, sessions/, __pycache__)…"
cd "$(dirname "$DEPLOY_DIR")"  # go one level up to intern_hunter parent
tar -czf "$TARBALL" \
    --exclude='intern_hunter/.env*' \
    --exclude='intern_hunter/data/*' \
    --exclude='intern_hunter/sessions/*' \
    --exclude='intern_hunter/credentials/*' \
    --exclude='intern_hunter/__pycache__' \
    --exclude='intern_hunter/**/__pycache__' \
    --exclude='intern_hunter/*.pyc' \
    --exclude='intern_hunter/**/*.pyc' \
    --exclude='intern_hunter/.venv' \
    --exclude='intern_hunter/venv' \
    intern_hunter/

TARBALL_SIZE=$(du -sh "$TARBALL" | cut -f1)
ok "Package created: $TARBALL ($TARBALL_SIZE)"
cd "$DEPLOY_DIR"


# =============================================================================
# SSH HELPER
# =============================================================================
SSH_OPTS="-i ${ORACLE_SSH_KEY_PATH} -o StrictHostKeyChecking=no -o ConnectTimeout=30"
REMOTE="ubuntu@${ORACLE_VM_IP}"

_ssh() { ssh $SSH_OPTS "$REMOTE" "$@"; }
_scp() { scp $SSH_OPTS "$@"; }


# =============================================================================
# STEP 4 — TEST SSH + UPLOAD PROJECT
# =============================================================================
step "STEP 4/8 — Upload to Oracle VM"

info "Testing SSH connection to $ORACLE_VM_IP…"
if ! _ssh "echo 'SSH OK'" 2>/dev/null | grep -q "SSH OK"; then
    err "Cannot connect to $ORACLE_VM_IP. Check:"
    echo "    • VM is running (Oracle Console → Compute → Instances)"
    echo "    • SSH key path is correct: $ORACLE_SSH_KEY_PATH"
    echo "    • Port 22 is open (VCN → Security Lists → Ingress: TCP 22)"
    echo "    • Try manually: ssh -i $ORACLE_SSH_KEY_PATH ubuntu@$ORACLE_VM_IP"
    exit 1
fi
ok "SSH connection successful"

info "Uploading project to ${REMOTE}:~/ …"
_scp "$TARBALL" "${REMOTE}:~/"
ok "Upload complete"


# =============================================================================
# STEP 5 — REMOTE INSTALL
# =============================================================================
step "STEP 5/8 — Install Dependencies on VM"

